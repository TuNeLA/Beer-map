export function readPlan() {
  const plan = JSON.parse(fs.readFileSync(path.join(HERE, "plan.json"), "utf8"));
  const dir = path.join(HERE, "steps");
  plan.steps = fs.readdirSync(dir).filter((f) => /^step-\d+\.json$/.test(f)).map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))).sort((a, b) => a.step - b.step);
  plan.stepOf = {}; plan.steps.forEach((s) => Object.keys(s.parts).forEach((p) => (plan.stepOf[p] = s.step)));
  // key -> part ; stmt anchors
  plan.keyPart = {}; plan.anchors = [];
  const add = (part, L) => {
    (L.fns || []).forEach((n) => (plan.keyPart["fn:" + n] = part));
    (L.vars || []).forEach((n) => (plan.keyPart["var:" + n] = part));
    (L.stmts || []).forEach((a) => plan.anchors.push({ lines: a.split("\n"), part }));
  };
  plan.steps.forEach((s) => Object.entries(s.parts).forEach(([p, L]) => add(p, L)));
  add("app", plan.stays);
  return plan;
}
// target part of a chunk by its keys (fn/var name, statement anchor = its first trimmed lines; the longest anchor wins), or null = unknown
export function targetOf(plan, it) {
  if (it.kind !== "stmt") {
    const ts = new Set(it.keys.map((k) => plan.keyPart[k]).filter(Boolean));
    if (ts.size > 1) throw new Error("var " + it.names.join(",") + " goes to " + [...ts].join(" + ") + ": split the var line first");
    return ts.size ? [...ts][0] : null;
  }
  const L = stmtLines(it.norm); let best = null;
  for (const a of plan.anchors) {
    if (a.lines.length > L.length || (best && a.lines.length < best.lines.length)) continue;
    if (!a.lines.every((l, i) => l === L[i])) continue;
    if (best && best.lines.length === a.lines.length && best.part !== a.part) throw new Error("statement anchor matches 2 parts: " + L[0]);
    best = a;
  }
  return best ? best.part : null;
}

// ---------- text helpers ----------
export function applyEdits(text, edits) {
  edits = edits.slice().sort((a, b) => b.start - a.start);
  for (let i = 1; i < edits.length; i++) if (edits[i].end > edits[i - 1].start) throw new Error("overlapping edits at " + edits[i].start);
  for (const e of edits) text = text.slice(0, e.start) + e.text + text.slice(e.end);
  return text;
}

// Remove generated blocks; leave one marker line where the block was. Returns { text, fields } (fields = PN.s entries of core).
export function strip(raw, part) {
  const lines = raw.split("\n"), out = [], fields = [];
  let inBlk = null, inS = false;
  for (const l of lines) {
    if (inBlk) {
      if (new RegExp("^\\s*// </split:" + inBlk + ">").test(l)) { inBlk = null; continue; }
      if (inBlk === "core") {
        if (/^  PN\.s = \{\s*$/.test(l)) { inS = true; continue; }
        if (inS && /^  \};\s*$/.test(l)) { inS = false; continue; }
        if (inS) { const m = l.match(/^    ([\w$]+): (.*?),(\s*\/\/.*)?$/); if (!m) throw new Error("bad PN.s line in app-core.js: " + l); fields.push({ name: m[1], init: m[2], comment: m[3] || "" }); }
      }
      continue;
    }
    const b = l.match(/^\s*\/\/ <split:(imports|core)>/);
    if (b) { inBlk = b[1]; out.push(b[1] === "core" ? CORE_MARK : IMP_MARK); continue; }
    if (l.trimEnd().endsWith(PUT_MARK)) continue;
    out.push(l);
  }
  if (inBlk) throw new Error(part + ": unclosed <split:" + inBlk + "> block");
  if (!out.includes(IMP_MARK)) {   // app.js before step 1: marker after the "use strict" line
    if (part !== "app") throw new Error(part + ": no <split:imports> block");
    const i = out.findIndex((l) => /^\s*"use strict";\s*$/.test(l));
    if (i < 0) throw new Error("app.js: no \"use strict\" line");
    out.splice(i + 1, 0, IMP_MARK);
  }
  return { text: out.join("\n"), fields };
}

// ---------- parse + items ----------
export function parse(text, label) {
  let comments = [];
  let ast;
  try { ast = acorn.parse(text, { ecmaVersion: "latest", sourceType: "script", locations: true, onComment: comments }); }
  catch (e) { throw new Error(label + ": parse error " + e.message); }
  const st = ast.body.find((s) => s.type === "ExpressionStatement" && s.expression.type === "CallExpression" && /Function/.test(s.expression.callee.type));
  if (!st) throw new Error(label + ": no IIFE");
  const fn = st.expression.callee;
  const lines = text.split("\n");
  const marker = lines.indexOf(IMP_MARK) + 1;   // 1-based line of the marker
  const body = fn.body.body.filter((s) => s.loc.start.line > marker);
  return { text, lines, ast, fn, body, marker, endLine: fn.body.loc.end.line, comments };
}

const isPNs = (n) => n && n.type === "MemberExpression" && !n.computed && n.object.type === "MemberExpression" && !n.object.computed &&
  n.object.object.type === "Identifier" && n.object.object.name === "PN" && n.object.property.name === "s";
export const pnsField = (st) => (st.type === "ExpressionStatement" && st.expression.type === "AssignmentExpression" && st.expression.operator === "=" && isPNs(st.expression.left) ? st.expression.left.property.name : null);

// One item per top-level statement. A chunk (group) = the gap lines before it (comments, blank lines) + its lines;
// statements that share a line are one group (they always move together).
export function items(P, label) {
  const out = [];
  let prevEnd = P.marker, g = -1;   // 1-based last line used
  for (let si = 0; si < P.body.length; si++) {
    const st = P.body[si], next = P.body[si + 1];
    const sL = st.loc.start.line, eL = st.loc.end.line;
    const join = sL <= prevEnd && out.length;
    if (!join) g++;
    if (!(next && next.loc.start.line <= eL)) {
      const after = P.lines[eL - 1].slice(st.loc.end.column);
      if (after.trim() && !/^\s*(\/\/.*|\/\*.*\*\/\s*)$/.test(after)) throw new Error(label + ":" + eL + ": text after the statement on its last line");
    }
    const it = { node: st, sL, eL, gapStart: join ? out[out.length - 1].gapStart : prevEnd + 1, grp: g, keys: [], names: [] };
    if (st.type === "FunctionDeclaration") { it.kind = "fn"; it.names = [st.id.name]; it.keys = ["fn:" + st.id.name]; }
    else if (st.type === "VariableDeclaration") { it.kind = "var"; it.names = st.declarations.map((d) => { if (d.id.type !== "Identifier") throw new Error(label + ": pattern var"); return d.id.name; }); it.keys = it.names.map((n) => "var:" + n); }
    else if (pnsField(st)) { it.kind = "svar"; it.names = []; it.field = pnsField(st); it.keys = ["var:" + it.field]; }
    else { it.kind = "stmt"; it.norm = P.text.slice(st.start, st.end).split("PN.s.").join(""); }
    out.push(it); prevEnd = Math.max(prevEnd, eL);
  }
  for (const it of out) it.gEnd = Math.max(...out.filter((x) => x.grp === it.grp).map((x) => x.eL));
  return out;
}
export function groups(its) { const G = []; for (const it of its) (G[it.grp] = G[it.grp] || []).push(it); return G; }
export const stmtLines = (norm) => norm.split("\n").map((l) => l.trim());

// ---------- scopes ----------
function patNames(p, out) {
  if (!p) return out;
  if (p.type === "Identifier") out.add(p.name);
  else if (p.type === "AssignmentPattern") patNames(p.left, out);
  else if (p.type === "ObjectPattern") p.properties.forEach((q) => patNames(q.type === "RestElement" ? q.argument : q.value, out));
  else if (p.type === "ArrayPattern") p.elements.forEach((e) => patNames(e, out));
  else if (p.type === "RestElement") patNames(p.argument, out);
  return out;
}
function hoisted(node, out) {   // var names of a function body (not nested functions)
  if (!node || typeof node.type !== "string") return out;
  if (/Function/.test(node.type)) return out;
  if (node.type === "VariableDeclaration" && node.kind === "var") node.declarations.forEach((d) => patNames(d.id, out));
  for (const k in node) { if (k === "loc") continue; const v = node[k]; if (Array.isArray(v)) v.forEach((c) => c && hoisted(c, out)); else if (v && typeof v.type === "string") hoisted(v, out); }
  return out;
}
function blockDecls(stmts, out) {   // let/const/class/function directly in a block (strict mode: block-scoped functions)
  for (const s of stmts) {
    if (s.type === "VariableDeclaration" && s.kind !== "var") s.declarations.forEach((d) => patNames(d.id, out));
    else if ((s.type === "FunctionDeclaration" || s.type === "ClassDeclaration") && s.id) out.add(s.id.name);
  }
  return out;
}
// Walk one top-level item. cb(ref) for each identifier that no inner scope declares:
// ref = { name, node, parent, key, write, call, load, shorthand }. load = runs while the file loads (not inside a non-IIFE function).
export function walkItem(st, cb) {
  const visit = (n, parent, key, scopes, deferred, isRoot) => {
    if (!n || typeof n.type !== "string") return;
    const T = n.type;
    if (T === "FunctionDeclaration" || T === "FunctionExpression" || T === "ArrowFunctionExpression") {
      const iife = parent && parent.type === "CallExpression" && key === "callee";
      const d2 = isRoot || iife ? deferred : true;
      const s = new Set();
      n.params.forEach((p) => patNames(p, s));
      if (T === "FunctionExpression" && n.id) s.add(n.id.name);
      if (T !== "ArrowFunctionExpression") s.add("arguments");
      if (n.body.type === "BlockStatement") { hoisted(n.body, s); blockDecls(n.body.body, s); }
      const sc = scopes.concat([s]);
      n.params.forEach((p) => visitPat(p, sc, d2));
      if (n.body.type === "BlockStatement") n.body.body.forEach((c) => visit(c, n.body, "body", sc, d2));
      else visit(n.body, n, "body", sc, d2);
      return;
    }
    if (T === "BlockStatement" || T === "StaticBlock") { const sc = scopes.concat([blockDecls(n.body, new Set())]); n.body.forEach((c) => visit(c, n, "body", sc, deferred)); return; }
    if (T === "SwitchStatement") { visit(n.discriminant, n, "discriminant", scopes, deferred); const s = new Set(); n.cases.forEach((c) => blockDecls(c.consequent, s)); const sc = scopes.concat([s]); n.cases.forEach((c) => { visit(c.test, c, "test", sc, deferred); c.consequent.forEach((x) => visit(x, c, "consequent", sc, deferred)); }); return; }
    if (T === "ForStatement" || T === "ForInStatement" || T === "ForOfStatement") {
      const head = T === "ForStatement" ? n.init : n.left; const s = new Set();
      if (head && head.type === "VariableDeclaration" && head.kind !== "var") head.declarations.forEach((d) => patNames(d.id, s));
      const sc = scopes.concat([s]);
      if (T !== "ForStatement" && n.left.type === "Identifier") ref(n.left, n, "left", sc, deferred, true);
      for (const k of T === "ForStatement" ? ["init", "test", "update", "body"] : ["left", "right", "body"]) { if (T !== "ForStatement" && k === "left" && n.left.type === "Identifier") continue; visit(n[k], n, k, sc, deferred); }
      return;
    }
    if (T === "CatchClause") { const s = patNames(n.param, new Set()); const sc = scopes.concat([s]); visit(n.body, n, "body", sc, deferred); return; }
    if (T === "VariableDeclarator") { visitPat(n.id, scopes, deferred); visit(n.init, n, "init", scopes, deferred); return; }
    if (T === "ClassDeclaration" || T === "ClassExpression") { visit(n.superClass, n, "superClass", scopes, deferred); visit(n.body, n, "body", scopes, deferred); return; }
    if (T === "Identifier") { ref(n, parent, key, scopes, deferred, false); return; }
    if (T === "MemberExpression") { visit(n.object, n, "object", scopes, deferred); if (n.computed) visit(n.property, n, "property", scopes, deferred); return; }
    if (T === "Property" || T === "MethodDefinition" || T === "PropertyDefinition") {
      if (n.computed) visit(n.key, n, "key", scopes, deferred);
      if (n.shorthand && n.value.type === "Identifier") { ref(n.value, n, "value", scopes, deferred, false, true); return; }
      visit(n.value, n, "value", scopes, deferred); return;
    }
    if (T === "LabeledStatement") { visit(n.body, n, "body", scopes, deferred); return; }
    if (T === "BreakStatement" || T === "ContinueStatement" || T === "MetaProperty") return;
    if (T === "AssignmentExpression" && n.left.type === "Identifier") { ref(n.left, n, "left", scopes, deferred, true); visit(n.right, n, "right", scopes, deferred); return; }
    if (T === "UpdateExpression" && n.argument.type === "Identifier") { ref(n.argument, n, "argument", scopes, deferred, true); return; }
    for (const k in n) { if (k === "loc" || k === "type" || k === "start" || k === "end") continue; const v = n[k]; if (Array.isArray(v)) v.forEach((c) => c && typeof c.type === "string" && visit(c, n, k, scopes, deferred)); else if (v && typeof v.type === "string") visit(v, n, k, scopes, deferred); }
  };
  const visitPat = (p, scopes, deferred) => {   // declarations: only default values are reads
    if (!p) return;
    if (p.type === "AssignmentPattern") { visitPat(p.left, scopes, deferred); visit(p.right, p, "right", scopes, deferred); }
    else if (p.type === "ObjectPattern") p.properties.forEach((q) => { if (q.computed) visit(q.key, q, "key", scopes, deferred); visitPat(q.type === "RestElement" ? q.argument : q.value, scopes, deferred); });
    else if (p.type === "ArrayPattern") p.elements.forEach((e) => visitPat(e, scopes, deferred));
    else if (p.type === "RestElement") visitPat(p.argument, scopes, deferred);
  };
  const ref = (id, parent, key, scopes, deferred, write, shorthand) => {
    if (scopes.some((s) => s.has(id.name))) return;
    cb({ name: id.name, node: id, parent, key, write: !!write, call: !!(parent && parent.type === "CallExpression" && key === "callee"), load: !deferred, shorthand: !!shorthand });
  };
  if (st.type === "FunctionDeclaration") visit(st, null, null, [], false, true);
  else if (st.type === "VariableDeclaration") st.declarations.forEach((d) => visit(d.init, d, "init", [], false));
  else visit(st, null, null, [], false);
}

