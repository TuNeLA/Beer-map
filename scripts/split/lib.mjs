// get(part) -> raw text or null. Returns { files: {part: {raw, text, P, items}}, fields, owner }
export function loadApp(get) {
  const A = { files: {}, fields: [] };
  for (const part of ORDER) {
    const raw = get(part); if (raw == null) continue;
    const s = strip(raw, part);
    if (part === "core") A.fields = s.fields;
    A.files[part] = { part, raw, text: s.text };
  }
  if (!A.files.app) throw new Error("docs/app.js missing");
  reparse(A);
  return A;
}
export function reparse(A, only) {
  for (const f of Object.values(A.files)) {
    if (only && f.part !== only) continue;
    f.refs = null;
    f.P = parse(f.text, relOf(f.part));
    f.items = items(f.P, relOf(f.part));
  }
  A.owner = {};
  for (const f of Object.values(A.files)) for (const it of f.items) for (const n of it.names) {
    if (A.owner[n]) throw new Error("name " + n + " declared twice: " + relOf(A.owner[n].file) + " and " + relOf(f.part));
    A.owner[n] = { file: f.part, item: it };
  }
  return A;
}
// refs per file: name -> [{ref, item}]
export function refsOf(f) {
  if (f.refs) return f.refs;
  const R = {};
  for (const it of f.items) walkItem(it.node, (r) => { (R[r.name] = R[r.name] || []).push(Object.assign(r, { item: it })); });
  return (f.refs = R);
}
export function fieldNames(A) {
  const s = new Set(A.fields.map((x) => x.name));
  for (const f of Object.values(A.files)) for (const it of f.items) if (it.kind === "svar") s.add(it.field);
  return s;
}

// ---------- generated blocks ----------
const wrap = (pieces, first, indent, sep, max) => {   // join pieces into lines of at most max chars
  const out = []; let cur = first;
  pieces.forEach((p, i) => { const add = (cur === first ? "" : sep) + p; if (cur !== first && (cur + add).length > max) { out.push(cur + sep.trimEnd()); cur = indent + p; } else cur += add; });
  out.push(cur); return out;
};
export function imports(A) {
  const files = Object.values(A.files), out = {};
  const rank = (n) => { const o = A.owner[n]; return ORDER.indexOf(o.file) * 1e7 + A.files[o.file].items.indexOf(o.item) * 100 + o.item.names.indexOf(n); };
  for (const f of files) out[f.part] = { fns: new Set(), vars: new Set(), exportFns: [], exportVars: new Set() };
  for (const f of files) {
    const R = refsOf(f);
    for (const n of Object.keys(R)) {
      const o = A.owner[n]; if (!o || o.file === f.part) continue;
      (o.item.kind === "fn" ? out[f.part].fns : out[f.part].vars).add(n);
    }
  }
  for (const f of files) {
    for (const n of [...out[f.part].fns, ...out[f.part].vars]) {
      const o = A.owner[n];
      if (RESERVED.includes(n)) throw new Error("name " + n + " is reserved on PN (SPEC 1.5)");
      if (o.item.kind === "fn") out[o.file].exportFns.push(n); else out[o.file].exportVars.add(n);
    }
  }
  for (const k in out) { const o = out[k]; o.fns = [...o.fns].sort((a, b) => rank(a) - rank(b)); o.vars = [...o.vars].sort((a, b) => rank(a) - rank(b)); o.exportFns = [...new Set(o.exportFns)].sort((a, b) => rank(a) - rank(b)); }
  return out;
}
// cross-file mutable vars: declared with var, written outside the declaration somewhere, used in 2+ files -> must be PN.s
export function needState(A) {
  const need = new Set(); const files = Object.values(A.files);
  for (const n in A.owner) {
    const o = A.owner[n]; if (o.item.kind !== "var") continue;
    let written = false, other = false;
    for (const f of files) { const r = refsOf(f)[n]; if (!r) continue; if (f.part !== o.file) other = true; if (r.some((x) => x.write)) written = true; }
    if (written && other) need.add(n);
  }
  return need;
}

const header = (plan, part) => "/* PintsNow app part: " + plan.purpose[part] + ". Moved from app.js without change (W2 step " + plan.stepOf[part] + "). Shared state: PN.s (app-core.js). */";
export function render(A, plan) {
  const imp = imports(A), res = {};
  for (const f of Object.values(A.files)) {
    const I = imp[f.part], L = f.P.lines;
    const blk = ["  // <split:imports> " + GEN];
    if (f.part === "app") blk.push("  var PN = window.PN;");
    if (I.vars.length) {
      blk.push(...wrap(I.vars, "  var ", "  var ", ", ", 118).map((l) => (l.endsWith(",") ? l.slice(0, -1) + ";" : l + ";")));
      const asg = I.vars.map((n) => n + " = PN." + n + ";");
      const one = "  PN.link(function () { " + asg.join(" ") + " });";
      if (one.length <= 118) blk.push(one); else blk.push("  PN.link(function () {", ...wrap(asg, "    ", "    ", " ", 118), "  });");
    }
    I.fns.forEach((n) => blk.push("  function " + n + "() { return PN." + n + ".apply(null, arguments); }"));
    if (I.exportFns.length) {
      const kv = I.exportFns.map((n) => n + ": " + n);
      const one = "  PN.put({ " + kv.join(", ") + " });";
      if (one.length <= 118) blk.push(one); else blk.push("  PN.put({", ...wrap(kv, "    ", "    ", ", ", 118), "  });");
    }
    blk.push("  // </split:imports>");
    // put lines after the statements that declare exported vars
    const putAfter = {};
    for (const it of f.items) if (it.kind === "var") { const ex = it.names.filter((n) => I.exportVars.has(n)); if (ex.length) putAfter[it.gEnd] = (putAfter[it.gEnd] || []).concat(ex); }
    for (const k in putAfter) putAfter[k] = "  PN.put({ " + putAfter[k].map((n) => n + ": " + n).join(", ") + " });   " + PUT_MARK;
    const out = [];
    const mi = f.P.marker - 1;
    if (f.part === "app") out.push(...L.slice(0, mi));
    else {
      out.push(header(plan, f.part), "(function () {", '  "use strict";');
      if (f.part !== "core") out.push("  var PN = window.PN;");
      else {
        out.push("  // <split:core> " + GEN + " (PN.put, PN.link, PN.s; a start value is checked against plan.json and the move base: do not edit it by hand)",
          "  var PN = window.PN, links = [];",
          "  PN.put = function (o) { for (var k in o) { if (PN.reserved.indexOf(k) >= 0) { PN.putBad(k); continue; } PN[k] = o[k]; } for (var i = 0; i < links.length; i++) links[i](); };",
          "  PN.link = function (fn) { links.push(fn); fn(); };",
          "  PN.s = {", ...A.fields.map((x) => "    " + x.name + ": " + x.init + "," + x.comment), "  };",
          "  // </split:core>");
      }
    }
    out.push(...blk);
    for (let i = mi + 1; i < L.length; i++) { out.push(L[i]); if (putAfter[i + 1]) out.push(putAfter[i + 1]); }
    res[f.part] = out.join("\n");
  }
  return res;
}
// index.html: part tags right before app.js, in ORDER; ?v= = sha256[:10] of the file (only if the app.js tag has ?v=)
export function renderIndex(html, texts) {
  const lines = html.split("\n").filter((l) => !/<script\b[^>]*src="\.\/js\/app-[a-z]+\.js/.test(l));
  const ai = lines.findIndex((l) => /<script\b[^>]*src="\.\/app\.js/.test(l));
  if (ai < 0) throw new Error("index.html: no app.js tag");
  const stamp = /src="\.\/app\.js\?v=/.test(lines[ai]);
  const tag = (src, t) => '<script defer src="./' + src + (stamp ? "?v=" + sha10(t) : "") + '"></script>';
  const parts = ORDER.filter((p) => p !== "app" && texts[p] != null);
  lines.splice(ai, 1, ...parts.map((p) => tag("js/app-" + p + ".js", texts[p])), stamp ? lines[ai].replace(/(src="\.\/app\.js)\?v=[0-9a-f]+/, "$1?v=" + sha10(texts.app)) : lines[ai]);
  return lines.join("\n");
}
