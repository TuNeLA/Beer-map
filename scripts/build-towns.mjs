#!/usr/bin/env node
// PintsNow — build docs/js/towns-data.js: every Swedish tätort (SCB "Statistiska tätorter 2023", 2 017 places) with
// name, centre, radius, population and kommun, plus the demonym the app knows (docs/js/hometown.js DEMONYM).
// Why (E7, data-sources.md item 10): the app named towns with Nominatim from the phone. Its usage policy calls periodic
// app requests "bulk geocoding". Now the phone finds the nearest town in this file (js/towns.js). No network.
// Source: SCB open geodata WFS layer stat:Tatorter_2023 (polygons, EPSG:4326). Licence: CC0 ("Vi använder licensen CC0",
// https://www.scb.se/om-scb/om-scb.se-och-anvandningsvillkor/oppna-data-api/). No credit is required; we still name SCB.
// Run once a year (SCB publishes new tätorter every 2-3 years):
//   node scripts/build-towns.mjs                 (fetches the WFS in pages of 250)
//   TOWNS_SRC_DIR=<dir> node scripts/build-towns.mjs   (reads <dir>/p*.json pages saved before, for offline runs)
// Output row: [name, lat, lng, r (m), pop, kommun index]. r = radius of a circle with the tätort's land area.
// The centre = area-weighted centroid of the largest polygon (a tätort in many parts is named after its main part).
import fs from "node:fs";
import path from "node:path";

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.join(repo, "docs/js/towns-data.js");
const WFS = "https://geodata.scb.se/geoserver/stat/wfs?service=WFS&version=2.0.0&request=GetFeature&typeNames=stat:Tatorter_2023" +
  "&outputFormat=application/json&srsName=EPSG:4326&sortBy=objectid&count=250&startIndex=";
const UA = "PintsNow-towns/1.0 (+https://github.com/TuNeLA/Beer-map; yearly town list)";

async function pages() {
  const dir = process.env.TOWNS_SRC_DIR;
  if (dir) return fs.readdirSync(dir).filter((f) => /^p\d+\.json$/.test(f)).map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
  const out = [];
  for (let s = 0; s < 5000; s += 250) {
    let j = null;
    for (let t = 0; t < 3 && !j; t++) {
      try { const r = await fetch(WFS + s, { headers: { "User-Agent": UA } }); if (r.ok) j = await r.json(); } catch (e) { /* retry */ }
    }
    if (!j) throw new Error("SCB WFS page " + s + " failed");
    out.push(j);
    if (!j.features || j.features.length < 250) break;
  }
  return out;
}

// Planar centroid of one ring set (outer ring minus holes); lng is scaled by cos(lat) so the weights are fair.
function polyCentroid(rings) {
  let A = 0, X = 0, Y = 0;
  const k = Math.cos((rings[0][0][1] * Math.PI) / 180);
  rings.forEach((ring, i) => {
    let a = 0, x = 0, y = 0;
    for (let j = 0; j < ring.length - 1; j++) {
      const x0 = ring[j][0] * k, y0 = ring[j][1], x1 = ring[j + 1][0] * k, y1 = ring[j + 1][1];
      const c = x0 * y1 - x1 * y0; a += c; x += (x0 + x1) * c; y += (y0 + y1) * c;
    }
    a /= 2;
    const s = i === 0 ? 1 : -1;
    if (Math.abs(a) > 0) { A += s * Math.abs(a); X += s * Math.abs(a) * (x / (6 * a)); Y += s * Math.abs(a) * (y / (6 * a)); }
  });
  return A > 0 ? { a: A, lng: X / A / k, lat: Y / A } : null;
}
function centre(geom) {
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.type === "MultiPolygon" ? geom.coordinates : [];
  let best = null;
  polys.forEach((p) => { const c = polyCentroid(p); if (c && (!best || c.a > best.a)) best = c; });
  return best;
}
function demonyms() {
  const src = fs.readFileSync(path.join(repo, "docs/js/hometown.js"), "utf8");
  const m = src.match(/var DEMONYM = \{([\s\S]*?)\};/);
  const out = {};
  if (m) for (const x of m[1].matchAll(/"([^"]+)":\s*"([^"]+)"/g)) out[x[1].toLowerCase()] = x[2];
  return out;
}

export function buildRows(feats, dem) {
  const kom = [], komIx = {}, rows = [];
  feats.forEach((f) => {
    const p = f.properties || {}, c = f.geometry && centre(f.geometry);
    if (!c || !p.tatort) return;
    const k = String(p.kommunnamn || "");
    if (!(k in komIx)) { komIx[k] = kom.length; kom.push(k); }
    const r = Math.round(Math.sqrt(((+p.area_ha || 0) * 10000) / Math.PI));
    const row = [String(p.tatort).trim(), +c.lat.toFixed(4), +c.lng.toFixed(4), r, +p.bef || 0, komIx[k]];
    rows.push(row);
  });
  // the biggest town of a name gets the demonym (two "Lund": only the city is "Lundabo")
  rows.sort((a, b) => b[4] - a[4] || (a[0] < b[0] ? -1 : 1));
  const used = {};
  rows.forEach((row) => { const d = dem[row[0].toLowerCase()]; if (d && !used[row[0].toLowerCase()]) { used[row[0].toLowerCase()] = 1; row.push(d); } });
  return { kom, rows };
}

async function main() {
  const feats = (await pages()).flatMap((j) => j.features || []);
  if (feats.length < 1900) throw new Error("only " + feats.length + " tätorter: keep the old file");   // safety floor
  const { kom, rows } = buildRows(feats, demonyms());
  const head = "/* GENERATED by scripts/build-towns.mjs (do not edit by hand). Swedish tätorter: SCB Statistiska tätorter 2023, CC0.\n" +
    "   Row: [name, lat, lng, r (m), population, kommun index (K), demonym (optional)]. Read by js/towns.js. */\n";
  // 25 rows per line: the file stays far under the 1200-line module limit of tests/quality/check.mjs
  const lines = [];
  for (let i = 0; i < rows.length; i += 25) lines.push(rows.slice(i, i + 25).map((r) => JSON.stringify(r)).join(","));
  const body = "window.TOWNS_DATA = {\n  v: 1, src: \"SCB Tätorter 2023 (CC0)\",\n  K: " + JSON.stringify(kom) + ",\n  T: [\n" + lines.join(",\n") + "\n  ]\n};\n";   // data, not a hook module: no PN.mod (like js/taxi-data.js)
  fs.writeFileSync(OUT, head + body);
  console.log("towns-data.js: " + rows.length + " towns, " + kom.length + " kommuner, " + rows.filter((r) => r[6]).length + " demonyms, " +
    Math.round((head + body).length / 1024) + " KB");
}
if (import.meta.url === "file://" + process.argv[1]) main().catch((e) => { console.error(e.message); process.exit(1); });
